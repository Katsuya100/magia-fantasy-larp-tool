function normalize(value) {
  return String(value ?? '').normalize('NFKC').toLowerCase()
    .replace(/[ァ-ヶ]/g, character => String.fromCharCode(character.charCodeAt(0) - 96))
    .replace(/[\p{White_Space}\p{P}\p{S}\u200B-\u200D\uFEFF]/gu, '');
}

const entries = [...new Set(ngWords.map(normalize))];
// Additional unambiguous, short threats missed by the upstream dictionary.
const explicitThreats = ['死ね', 'しね', '殺す', 'ころす', 'レイプ', '強姦', 'ちんこ', 'ちんぽ', 'まんこ'].map(normalize);

export function isDungeonNameBlocked(name) {
  const input = normalize(name);
  if (!input) return false;
  if (explicitThreats.some(word => input.includes(word))) return true;
  // Short ambiguous substrings must match the whole name so "カスミ" stays valid.
  return entries.some(word => word.length >= 4 ? input.includes(word) : input === word);
}

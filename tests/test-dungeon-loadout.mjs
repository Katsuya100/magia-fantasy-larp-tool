import assert from 'node:assert/strict';
import {GRID_COLUMNS,normalizeSlots,prepareCircles,prepareItems,setSlot,pickedValues,isFull,ensureItemInstances,saveCarrySlots,restoreCarrySlots,validCarrySlots} from '../assets/js/dungeon-loadout.mjs';
import {spellGrid,itemGrid,circleChoices,itemChoices} from '../assets/js/dungeon-preparation-ui.mjs';
const esc=s=>String(s).replace(/[&<>"]/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[x]));
assert.equal(GRID_COLUMNS,5);
const ids=['a','b','c','d','e','f'];
assert.deepEqual(prepareCircles(['a','b'],ids),['a','b',null,null,null],'legacy compact loadout becomes positional');
assert.deepEqual(prepareCircles(['a',null,'b','a','obsolete'],ids),['a',null,'b',null,null],'gaps maintained, duplicates and deleted IDs removed');
assert.deepEqual(prepareCircles(['a','b','c','d','e'],ids),['a','b','c','d','e']);
let spells=prepareCircles(['a','b',null,null,null],ids);
spells=setSlot(spells,0,'b');
assert.deepEqual(spells,['b','a',null,null,null],'swaps existing slot');
spells=setSlot(spells,4,'a');
assert.deepEqual(spells,['b',null,null,null,'a'],'moves a spell without duplicates');
spells=setSlot(spells,4,null);
assert.deepEqual(spells,['b',null,null,null,null]);
assert.throws(()=>setSlot(spells,5,'a'),/Invalid slot/);
assert.equal(isFull(spells),false);
assert.equal(isFull(['a','b','c','d','e']),true);
assert.deepEqual(pickedValues([0,null,3,null]),[0,3]);
const inventory=[{id:'heal_s',value:24},{id:'mana_s',value:12},{id:'clear_flame',value:0}];
assert.deepEqual(prepareItems([],inventory.length,3),[null,null,null,null,null]);
assert.equal(prepareItems([],inventory.length,15).length,15);
assert.deepEqual(prepareItems([0,null,1,0,7],inventory.length,3),[0,null,1,null,null]);
let equipped=prepareItems([0,1,2],inventory.length,3);
equipped=setSlot(equipped,0,1);
assert.deepEqual(equipped.slice(0,3),[1,0,2]);
const inventoryProfile={
 inventory:[{id:'heal_s',value:25},{id:'heal_s',value:25},{id:'heal_s',value:25}],
 run:null
};
let number=0;
assert.equal(ensureItemInstances(inventoryProfile,()=>String(++number)),true);
assert.equal(ensureItemInstances(inventoryProfile,()=>String(++number)),false,'IDs are assigned only once');
assert.equal(new Set(inventoryProfile.inventory.map(x=>x.instanceId)).size,3,'identical potion types have unique IDs');
const equippedSlots=[1,null,0,null,2];
const savedIds=saveCarrySlots(equippedSlots,inventoryProfile.inventory);
assert.deepEqual(restoreCarrySlots(savedIds,inventoryProfile.inventory,3),equippedSlots,'slots retain their original positions');
assert.deepEqual(restoreCarrySlots(savedIds,[...inventoryProfile.inventory].reverse(),3),[1,null,2,null,0],'reordering inventory does not break selection');
const survived=[inventoryProfile.inventory[0],inventoryProfile.inventory[2]];
assert.deepEqual(validCarrySlots(savedIds,survived,3),[null,null,inventoryProfile.inventory[0].instanceId,null,inventoryProfile.inventory[2].instanceId],'consumed potion does not reappear in saved loadout');
assert.deepEqual(restoreCarrySlots(savedIds,survived,3),[null,null,0,null,1],'surviving potions return to old slot numbers');
inventoryProfile.run={carry:[{id:'mana_s',value:15,instanceId:inventoryProfile.inventory[0].instanceId},null]};
assert.equal(ensureItemInstances(inventoryProfile,()=>String(++number)),true,'legacy battle item with duplicate identity gets repaired');
assert.notEqual(inventoryProfile.run.carry[0].instanceId,inventoryProfile.inventory[0].instanceId);
const upgraded=restoreCarrySlots(savedIds,inventoryProfile.inventory,15);
assert.equal(upgraded.length,15,'higher level keeps five-column rows');
const circles=ids.slice(0,5).map((id,i)=>({id,name:'魔法陣'+i,image:new Blob(['x']),analysis:null}));
const makeImg=()=>('blob:mock');
const spellHtml=spellGrid(prepareCircles([],ids),circles,makeImg,esc);
assert.equal((spellHtml.match(/data-open-slot=/g)||[]).length,5);
assert.equal((spellHtml.match(/class="loadout-tile empty"/g)||[]).length,5);
assert.match(spellGrid(['a',null,null,null,null],circles,makeImg,esc),/data-open-slot="0"/);
assert.doesNotMatch(spellGrid(['a',null,null,null,null],circles,makeImg,esc),/魔法陣\s*0[1-9]|魔法陣0/);
assert.doesNotMatch(spellGrid(['a',null,null,null,null],circles,makeImg,esc),/魔法陣0/,'legacy names remain hidden');
assert.match(spellGrid(['a',null,null,null,null],circles,makeImg,esc),/<img alt="" src="blob:mock"/);
const itemName=x=>x.id;
const beforeReturn=itemGrid(prepareItems([],3,3),inventory,3,false,itemName,esc);
assert.equal((beforeReturn.match(/data-open-item=/g)||[]).length,0,'no locked item slots show before the first return');
assert.doesNotMatch(beforeReturn,/未解放|class="loadout-tile locked"/,'locked item tiles do not render');
const afterReturn=itemGrid(prepareItems([0,1,2],3,3),inventory,3,true,itemName,esc);
assert.equal((afterReturn.match(/data-open-item=/g)||[]).length,3,'only current level capacity visible after return');
assert.equal((afterReturn.match(/class="loadout-tile locked"/g)||[]).length,0);
assert.equal((afterReturn.match(/class="loadout-tile equipped"/g)||[]).length,3);
const maxItemGrid=itemGrid(prepareItems([],3,15),inventory,15,true,itemName,esc);
assert.equal((maxItemGrid.match(/data-open-item=/g)||[]).length,15,'later item slots become additional rows');
assert.equal((circleChoices(circles,['a'],makeImg,esc).match(/data-choose-circle=/g)||[]).length,5);
assert.doesNotMatch(circleChoices(circles,['a'],makeImg,esc),/魔法陣\s*0[1-9]|魔法陣0/,'picker shows no circle names');
assert.equal((itemChoices(inventory,[0],itemName,esc).match(/data-choose-item=/g)||[]).length,3);
assert.match(circleChoices([],[],makeImg,esc),/魔導書に魔法陣を登録/);
assert.match(itemChoices([],[],itemName,esc),/携行品がありません/);
console.log('PASS indexed five-column spell/item slots, swap, upgrades, legacy data and picker markup');

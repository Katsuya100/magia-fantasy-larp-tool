import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as G from '../assets/js/dungeon-core.mjs';
import {configure} from '../assets/js/dungeon-tuning.mjs';
const csv=async name=>G.parseCsv(await readFile(new URL('../assets/data/dungeon-'+name+'.csv',import.meta.url),'utf8'));
const [balance,levels,floors,playerBase,buffs]=await Promise.all(['balance','levels','floors','player-base','buffs'].map(csv));
configure({balance,levels,floors,playerBase});
const hero=G.makeUnit({hp:100,mag:10,def:8,res:8},91,{},[{role:'support',attribute:'aqua',power:681}]);
const enemy=G.makeUnit({hp:100,mag:10,def:8,res:8},91,{},[{role:'basic',attribute:'law',power:0}]);
hero.hp-=500;
const before=hero.hp;
const steps=[];
G.round(hero,enemy,0,-1,buffs,()=>0.99,step=>steps.push(step));
assert.ok(hero.hp>before,'the same healing circle works during battle');
assert.ok(steps.some(step=>step.side==='hero'&&step.role==='support'&&step.amount>0));
const app=await readFile(new URL('../assets/js/dungeon-app.mjs',import.meta.url),'utf8');
const takeTurn=app.slice(app.indexOf('async function takeTurn('),app.indexOf('async function useItem('));
assert.match(takeTurn,/run\.stage!=='battle'/,'casting is gated on active battle');
assert.match(takeTurn,/if\(run\.enemy\.hp<=0\)/,'victory transitions away from battle');
assert.match(takeTurn,/run\.stage='checkpoint'/,'boss victory enters checkpoint');
assert.match(takeTurn,/run\.floor\+\+;enterFight\(\)/,'ordinary victory immediately enters next fight');
assert.fail('REPRO: a healing circle cannot activate on the post-victory screen, despite being selectable there');

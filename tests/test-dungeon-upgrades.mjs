import assert from 'node:assert/strict';
import {upgradeCircle,savedUpgrade,applySavedUpgrade,strengthenedPower,combatSpell,upgradeStoneCost,totalUpgradeStoneCost} from '../assets/js/dungeon-upgrades.mjs';
for(const [level,cost] of [[0,5],[1,5],[9,5],[19,5],[20,6],[59,6],[60,7],[99,7],[100,8],[149,9]])assert.equal(upgradeStoneCost(level),cost);
for(const [level,cost] of [[0,0],[1,5],[10,50],[11,55],[20,100],[21,106],[60,340],[150,1030]])assert.equal(totalUpgradeStoneCost(level),cost);
const original={id:'circle',analysis:{attribute:'flame',role:'attack',power:100},revealed:true};
let upgraded=upgradeCircle(original);
assert.equal(original.analysis.power,100,'original magic is not mutated');
assert.deepEqual({power:upgraded.analysis.power,base:upgraded.basePower,level:upgraded.upgradeLevel},{power:110,base:100,level:1});
for(let i=0;i<9;i++)upgraded=upgradeCircle(upgraded);
assert.equal(upgraded.analysis.power,200,'ten upgrades add 100% of original, not compound interest');
assert.equal(upgraded.basePower,100);
assert.equal(upgraded.upgradeLevel,10);
assert.deepEqual(combatSpell(upgraded),{...upgraded.analysis,basePower:100,upgradeLevel:10},'battle keeps increased power and original MP basis');
assert.equal(combatSpell(original).basePower,100,'ordinary spell uses its original power');
assert.equal(combatSpell(original).upgradeLevel,0,'unupgraded magic has visual tier I');
assert.equal(combatSpell({...original,upgradeLevel:55}).upgradeLevel,55,'ultimate investment reaches combat playback');
assert.equal(combatSpell({...original,upgradeLevel:-12}).upgradeLevel,0,'invalid legacy investment is ignored');
assert.equal(combatSpell({...original,analysis:null}),null,'unknown circle remains unavailable');
assert.equal(upgradeCircle({analysis:{power:33.3},upgradeLevel:0}).analysis.power,37,'fractional upgraded power rounds upward');
assert.equal(upgradeCircle({analysis:{power:33.3},basePower:33.3,upgradeLevel:1}).analysis.power,40,'subsequent upgrade rounds upward independently without compounding');
assert.equal(strengthenedPower(100,1),110,'floating-point representation cannot accidentally add 1');
assert.equal(strengthenedPower(11,1),13,'12.1 is rounded upward to 13');
const persisted=savedUpgrade(upgraded);
const reloaded=applySavedUpgrade({...original,image:new Blob(['photo'])},persisted);
assert.equal(reloaded.analysis.power,200,'profile upgrade metadata restores power after reloading the image');
assert.equal(reloaded.basePower,100);
assert.equal(reloaded.upgradeLevel,10);
assert.equal(combatSpell(reloaded).basePower,100,'loaded upgrade retains original casting MP');
assert.equal(combatSpell(reloaded).upgradeLevel,10,'loaded investment survives into visual playback');
assert.equal(applySavedUpgrade(original,null),original,'legacy photo records work without upgrade metadata');
const legacy={...original,basePower:33.3,upgradeLevel:1,
 analysis:{...original.analysis,power:36.63}};
const rounded=applySavedUpgrade(legacy,undefined);
assert.equal(rounded.analysis.power,37,'old photo-record power is rounded up on load, without rewriting the Blob');
assert.equal(legacy.analysis.power,36.63,'old photo record itself is not mutated');
assert.equal(applySavedUpgrade({...legacy,analysis:{...legacy.analysis,power:39.96},upgradeLevel:2},undefined).analysis.power,40,'legacy second upgrade rounds up');
assert.equal(applySavedUpgrade(legacy,{basePower:50,upgradeLevel:2}).analysis.power,60,'current profile metadata takes precedence over old circle upgrade');
assert.equal(applySavedUpgrade(original,{basePower:-1,upgradeLevel:9}),original,'invalid saved upgrades are ignored');
assert.throws(()=>upgradeCircle({analysis:{power:0}}),/強化できない/);
assert.throws(()=>upgradeStoneCost(-1),/無効な強化段階/);
console.log('PASS non-compounding magical-circle power upgrades');

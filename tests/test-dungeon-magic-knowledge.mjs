import assert from 'node:assert/strict';
import {canDepartWithCircles,equippedCircleCount,circleSummary,attributeEffectGuide,circleCardInfo,circleEffectDetails,
 newCapturedCircle,savePreanalysis,isRevealed,revealOnUse,circleDetails,
 normalizeAnalysisResult,spellEffect,ROLES} from '../assets/js/dungeon-magic-knowledge.mjs';
const eq=n=>Array.from({length:5},(_,i)=>i<n?'id-'+i:null);
for(let n=0;n<=5;n++)assert.equal(canDepartWithCircles(eq(n)),n>=3,'equipped count '+n);
assert.equal(canDepartWithCircles(['a','b','c']),false,'five visible slots required');
assert.equal(equippedCircleCount(['a',null,'b',null,'c']),3);
const circle=newCapturedCircle('photo',new Blob(['JPEG']),42);
assert.equal(circle.revealed,false);
assert.equal(circle.analysis,null);
const buffs=[{id:'buff_flame',name:'炎熱鼓舞',duration:2},{id:'debuff_flame',name:'火傷',duration:2}];
const pending=savePreanalysis(circle,{attribute:'flame',role:'防御',power:512});
assert.equal(isRevealed(pending),false);
assert.match(circleSummary(pending,buffs),/🔥 \/ 🛡️/);
assert.doesNotMatch(circleSummary(pending,buffs),/炎熱鼓舞/,'summary omits named effects');
assert.match(circleSummary(pending,buffs,p=>Math.ceil(p/100)),/MP:\? \/ 威力:\?/);
assert.deepEqual(circleCardInfo(pending,buffs,p=>Math.ceil(p/100)),
 {symbols:'🔥 / 🛡️',mp:'?',power:'?'},'all pre-use values are hidden');
assert.equal(circleDetails(pending,buffs,p=>Math.ceil(p/100)).mp,'?');
assert.equal(circleDetails(pending,buffs,p=>Math.ceil(p/100)).power,'?');
assert.doesNotMatch(circleSummary(pending,buffs),/512|\b6\b/);
const used=revealOnUse(pending);
assert.equal(isRevealed(used),true);
assert.match(circleSummary(used,buffs,p=>Math.ceil(p/100)),/MP:6 \/ 威力:512/);
assert.deepEqual(circleCardInfo(used,buffs,p=>Math.ceil(p/100)),
 {symbols:'🔥 / 🛡️',mp:'6',power:'512'});
assert.equal(circleDetails(used,buffs,p=>Math.ceil(p/100)).mp,'6');
assert.equal(circleDetails(used,buffs,p=>Math.ceil(p/100)).power,'512');
const enhanced={...used,basePower:512,analysis:{...used.analysis,power:1024}};
assert.match(circleSummary(enhanced,buffs,p=>Math.ceil(p/100)),/MP:6 \/ 威力:1024/,'summary keeps original MP while power increases');
assert.equal(circleCardInfo(enhanced,buffs,p=>Math.ceil(p/100)).mp,'6','card MP is unchanged after enhancement');
assert.equal(circleDetails(enhanced,buffs,p=>Math.ceil(p/100)).mp,'6','details MP is unchanged after enhancement');
assert.equal(circleDetails(enhanced,buffs,p=>Math.ceil(p/100)).power,'1024');
const attack=savePreanalysis(circle,{attribute:'bolt',role:'attack',power:512});
const support=savePreanalysis(circle,{attribute:'aqua',role:'support',power:512});
const debuff=savePreanalysis(circle,{attribute:'flame',role:'debuff',power:512});
assert.equal(circleCardInfo(attack,buffs).symbols,'⚡ / ⚔️');
assert.equal(circleCardInfo(support,buffs).symbols,'💧 / ✚');
assert.equal(circleEffectDetails(debuff,buffs).statusName,'火傷');
assert.equal(circleCardInfo(debuff,buffs).symbols,'🔥 / 🕸️');
assert.match(circleEffectDetails(pending,buffs).effect,/耐性/);
assert.match(circleEffectDetails(pending,buffs).statusDescription,/攻撃ダメージが増加/);
assert.match(circleEffectDetails(pending,buffs).duration,/2〜6ターン/);
assert.equal(circleEffectDetails(used,buffs,()=>4).duration,'4ターン（威力連動）');
assert.equal(circleEffectDetails(enhanced,buffs,()=>6).duration,'6ターン（威力連動）');
assert.equal(circleEffectDetails(pending,buffs,()=>4).duration,'2〜6ターン（威力連動）','unknown power does not reveal duration');
assert.match(circleEffectDetails(debuff,buffs).statusDescription,/継続ダメージ/);
assert.match(circleEffectDetails(debuff,buffs).duration,/2〜6ターン/);
assert.equal(circleEffectDetails(revealOnUse(debuff),buffs,()=>4).duration,'4ターン（威力連動）');
assert.equal(circleEffectDetails(attack,buffs).statusName,'');
assert.equal(circleEffectDetails(support,buffs).statusName,'');
const chaos=savePreanalysis(circle,{attribute:'chaos',role:'debuff',power:512});
assert.equal(circleEffectDetails(chaos,buffs).statusName,'弱体');
const chaosNamedBuffs=[...buffs,{id:'debuff_chaos',name:'暴走',duration:2}];
assert.equal(circleEffectDetails(chaos,chaosNamedBuffs).statusName,'暴走');
assert.match(spellEffect(chaos.analysis,chaosNamedBuffs),/暴走/);
assert.match(circleEffectDetails(chaos,chaosNamedBuffs).statusDescription,/暴走/);
assert.equal(circleEffectDetails(revealOnUse(chaos),buffs,()=>6).duration,'6ターン（威力連動）');
assert.equal(isRevealed({analysis:pending.analysis}),true,'legacy analyzed circles retain visible power');
assert.match(spellEffect({...pending.analysis,role:'debuff'},buffs),/🕸️火傷/);
assert.match(spellEffect({...pending.analysis,role:'attack'},buffs),/⚔️属性攻撃/);
assert.match(spellEffect({...pending.analysis,role:'support'},buffs),/✚HP回復/);
assert.equal(attributeEffectGuide(buffs).length,7);
assert.deepEqual(ROLES,{attack:'⚔️攻撃',defense:'🛡️防御',support:'✚回復',debuff:'🕸️弱体'});
assert.throws(()=>normalizeAnalysisResult({attribute:'invalid',role:'攻撃',power:1}),/不正/);
assert.throws(()=>normalizeAnalysisResult({attribute:'flame',role:'攻撃',power:-1}),/不正/);
assert.deepEqual(normalizeAnalysisResult({attribute:' flame ',role:'攻撃',power:'700'}),{attribute:'flame',role:'attack',power:700});
console.log('PASS magic knowledge, 3-5 slots, hidden pre-use power, MP and icon-labeled effects');

import assert from 'node:assert/strict';
import {createCircleImageUrls} from '../assets/js/dungeon-image-urls.mjs';
const generated=[],revoked=[];
const cache=createCircleImageUrls(blob=>{const url='blob:circle-'+(generated.length+1);generated.push({url,blob});return url;},url=>revoked.push(url));
const first=new Blob(['photo 1']),second=new Blob(['photo 2']);
const u1=cache.get(first);
assert.equal(cache.get(first),u1,'battle spells reuse the same photo URL after casts');
assert.equal(cache.get(first),u1,'returning from collection keeps the image alive');
assert.equal(generated.length,1,'one createObjectURL call per photo');
const u2=cache.get(second);
assert.notEqual(u1,u2);
assert.deepEqual(revoked,[],'rendering a subsequent fight must not revoke still visible photos');
cache.release(first);
assert.deepEqual(revoked,[u1],'deleting one photo revokes only its own URL');
assert.equal(cache.get(second),u2,'other images remain valid');
const updated=cache.get(first);
assert.notEqual(updated,u1,'released photo is refreshed only if explicitly asked again');
cache.releaseAll();
assert.deepEqual(revoked,[u1,u2,updated],'unloading revokes each remaining URL exactly once');
const recreated=cache.get(first);
assert.notEqual(recreated,updated,'relaunch creates new URL for photo');
cache.releaseAll();
console.log('PASS stable spell photo URLs through repeated battle redraws and controlled cleanup');

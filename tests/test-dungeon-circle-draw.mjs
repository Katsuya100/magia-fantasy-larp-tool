import assert from 'node:assert/strict';
import {DRAWN_GLYPH_LIMIT,DRAWN_POWER_RATE,drawnPower,pointOnPad,glyphPoint,sigilPoint,normalizedGlyph,createDrawingModel} from '../assets/js/dungeon-circle-draw.mjs';

assert.equal(DRAWN_GLYPH_LIMIT,32);
assert.equal(DRAWN_POWER_RATE,.6);
assert.equal(drawnPower(500),300);
assert.equal(drawnPower(200),120,'failure fallback receives the same 60% reduction');
assert.equal(drawnPower(1),1);
assert.throws(()=>drawnPower(NaN));
const pad={left:10,top:20,width:200,height:300};
assert.deepEqual(pointOnPad(110,170,pad),{x:0,y:0});
assert.deepEqual(pointOnPad(10,70,pad),{x:-1,y:-1});
const outer=sigilPoint({x:1,y:0});
assert.ok(outer.x>.5+.255,'sigil overflow is never clipped to the guide');
const top=glyphPoint({x:0,y:0},0);
assert.ok(Math.abs(top.x-.5)<1e-9&&top.y<.2);
const glyph=normalizedGlyph([[{x:-.1,y:-.2},{x:.1,y:.2}]]);
assert.equal(glyph.length,1);
assert.ok(glyph[0][0].x<0&&glyph[0][1].y>0);

const model=createDrawingModel();
assert.equal(model.enterGlyph(),false);
assert.equal(model.goSigil(),false);
assert.equal(model.addSpace(),false);
const stroke=[{x:0,y:-.3},{x:.2,y:.2}];
assert.equal(model.addStroke(stroke),true);
assert.equal(model.canUndo,true);
assert.equal(model.enterGlyph(),true);
assert.equal(model.state.letters.length,1);
assert.equal(model.state.ink.length,0);
assert.equal(model.addSpace(),true);
assert.equal(model.addSpace(),false,'no double word break');
assert.equal(model.undo(),true);
assert.equal(model.state.letters.length,1);
assert.equal(model.redo(),true);
assert.equal(model.state.letters.length,2);
assert.equal(model.goSigil(),true);
assert.equal(model.complete,false);
assert.equal(model.addStroke(stroke),true);
assert.equal(model.complete,true);
assert.equal(model.undo(),true);
assert.equal(model.complete,false);
assert.equal(model.redo(),true);
assert.equal(model.complete,true);
assert.equal(model.reset(),true);
assert.equal(model.complete,false);
model.goSpell();
assert.equal(model.state.letters.length,2,'moving back retains spell');
assert.equal(model.reset(),true);
assert.equal(model.state.letters.length,0);
assert.equal(model.undo(),true);
assert.equal(model.state.letters.length,2,'reset is undoable');
assert.equal(model.redo(),true);
assert.equal(model.state.letters.length,0);
for(let i=0;i<DRAWN_GLYPH_LIMIT;i++){
 model.addStroke(stroke);
 assert.equal(model.enterGlyph(),true);
}
assert.equal(model.state.letters.length,DRAWN_GLYPH_LIMIT);
assert.equal(model.enterGlyph(),false);
assert.equal(model.addSpace(),false);
assert.equal(model.goSigil(),true);
console.log('PASS touch magic-circle drawing, history, phase transitions, overflow and power reduction');

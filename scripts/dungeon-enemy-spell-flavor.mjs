export const undeadNames=/ゾンビ|スケルトン|骸骨|骨|ボーン|死霊|亡霊|幽霊|レイス|ゴースト|ファントム|バンシー|アンデッド|亡者|デスナイト|グール|ミイラ|吸血|ヴァンパイア|屍術王|リッチ|デュラハン|ドゥラハン|不死|スペクター/;

export function alignEnemySpellFlavor(input){
 return input.map(row=>{
  const wanted=enemySpellOverrides[row.id],isUndead=undeadNames.test(row.name);
  if(!wanted&&!isUndead)return {...row};
  const cells=row.spells.split('|').map(spell=>spell.split(':'));
  if(cells.length!==5||cells.some(x=>x.length!==3))throw Error('Invalid five-spell definition '+row.id);
  if(wanted){
   for(const slot of [0,1,3])cells[slot][1]=wanted[0];
   for(const slot of [2,4])cells[slot][1]=wanted[1];
  }
  if(isUndead)for(const spell of cells)if(spell[0]==='support')spell[0]='defense';
  return {...row,spells:cells.map(parts=>parts.join(':')).join('|')};
 });
}
